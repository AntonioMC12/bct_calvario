CREATE SCHEMA calvario;
REVOKE ALL ON SCHEMA calvario FROM PUBLIC;
SET LOCAL search_path TO calvario, pg_catalog;

CREATE TABLE schema_version (
  singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
  version INTEGER NOT NULL
);

-- Las marcas ISO en UTC mantienen el mismo orden y representación que en SQLite.
CREATE FUNCTION unixepoch(value TEXT) RETURNS BIGINT
LANGUAGE SQL STABLE STRICT SET search_path = pg_catalog AS $$
  SELECT floor(extract(epoch FROM value::timestamptz))::bigint
$$;
CREATE TABLE members (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  name TEXT NOT NULL,
  instrument TEXT NOT NULL,
  voice TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'musician' CHECK (role IN ('musician','admin','director')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','rejected','inactive')),
  created_at TEXT NOT NULL,
  reviewed_at TEXT,
  reviewed_by TEXT REFERENCES members(id) DEFERRABLE
);
CREATE TABLE sessions (
  token TEXT PRIMARY KEY,
  member_id TEXT NOT NULL REFERENCES members(id),
  expires BIGINT NOT NULL
);
CREATE TABLE events (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  type TEXT NOT NULL,
  starts TEXT NOT NULL,
  ends TEXT NOT NULL CHECK (ends > starts),
  location TEXT NOT NULL,
  town TEXT NOT NULL,
  meeting TEXT NOT NULL,
  description TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 1,
  cancelled INTEGER NOT NULL DEFAULT 0 CHECK (cancelled IN (0,1)),
  reminder_minutes INTEGER,
  reminder_sent INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE intentions (
  event_id TEXT NOT NULL REFERENCES events(id),
  member_id TEXT NOT NULL REFERENCES members(id),
  value TEXT NOT NULL CHECK (value IN ('yes','no','unset')),
  reason TEXT NOT NULL DEFAULT '',
  version INTEGER NOT NULL DEFAULT 1,
  updated_by TEXT NOT NULL REFERENCES members(id),
  updated_at TEXT NOT NULL,
  request_key TEXT,
  PRIMARY KEY(event_id, member_id)
);
CREATE TABLE presence (
  event_id TEXT NOT NULL REFERENCES events(id),
  member_id TEXT NOT NULL REFERENCES members(id),
  value TEXT NOT NULL CHECK (value IN ('present','absent','unset')),
  updated_by TEXT NOT NULL REFERENCES members(id),
  updated_at TEXT NOT NULL,
  PRIMARY KEY(event_id, member_id)
);
CREATE TABLE notices (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TEXT NOT NULL,
  event_id TEXT REFERENCES events(id),
  author_id TEXT REFERENCES members(id)
);
CREATE TABLE inbox (
  notice_id TEXT NOT NULL REFERENCES notices(id),
  member_id TEXT NOT NULL REFERENCES members(id),
  read_at TEXT,
  PRIMARY KEY(notice_id, member_id)
);
CREATE INDEX inbox_member ON inbox(member_id);
CREATE TABLE audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id TEXT NOT NULL REFERENCES members(id),
  action TEXT NOT NULL,
  target TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE formations (
  event_id TEXT PRIMARY KEY REFERENCES events(id),
  columns INTEGER NOT NULL,
  positions TEXT NOT NULL,
  version INTEGER NOT NULL
);
CREATE TABLE templates (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  columns INTEGER NOT NULL,
  size INTEGER NOT NULL
);
CREATE TABLE works (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  authors TEXT NOT NULL,
  genre TEXT NOT NULL
);
CREATE TABLE files (
  id TEXT PRIMARY KEY,
  work_id TEXT REFERENCES works(id),
  event_id TEXT REFERENCES events(id),
  name TEXT NOT NULL,
  instrument TEXT NOT NULL,
  voice TEXT NOT NULL,
  content BYTEA NOT NULL,
  digest TEXT NOT NULL,
  approved INTEGER NOT NULL CHECK (approved IN (0,1)),
  CHECK ((work_id IS NULL) <> (event_id IS NULL))
);
CREATE UNIQUE INDEX unique_score ON files(work_id, instrument, voice, digest) WHERE work_id IS NOT NULL;
CREATE UNIQUE INDEX unique_attachment ON files(event_id, digest) WHERE event_id IS NOT NULL;


ALTER TABLE members ADD COLUMN email_verified_at TEXT;
ALTER TABLE members ADD COLUMN requires_email_verification INTEGER NOT NULL DEFAULT 0
  CHECK (requires_email_verification IN (0, 1));

CREATE TABLE account_tokens (
  digest TEXT PRIMARY KEY,
  member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  purpose TEXT NOT NULL CHECK (purpose IN ('verify','reset')),
  created BIGINT NOT NULL,
  expires BIGINT NOT NULL
);
CREATE INDEX account_tokens_member ON account_tokens(member_id, purpose, created);
CREATE INDEX account_tokens_expiry ON account_tokens(expires);


ALTER TABLE members ADD COLUMN password_enabled INTEGER NOT NULL DEFAULT 1 CHECK (password_enabled IN (0, 1));

CREATE TABLE google_identities (
  google_subject TEXT PRIMARY KEY,
  firebase_uid TEXT NOT NULL UNIQUE,
  member_id TEXT NOT NULL UNIQUE REFERENCES members(id) ON DELETE CASCADE
);

CREATE TABLE push_subscriptions (
  id TEXT PRIMARY KEY,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  session_token TEXT NOT NULL REFERENCES sessions(token) ON DELETE CASCADE,
  member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE
);
CREATE INDEX push_member ON push_subscriptions(member_id);
CREATE INDEX push_session ON push_subscriptions(session_token);
CREATE TABLE push_jobs (
  notice_id TEXT NOT NULL REFERENCES notices(id) ON DELETE CASCADE,
  subscription_id TEXT NOT NULL REFERENCES push_subscriptions(id) ON DELETE CASCADE,
  due BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  lease TEXT,
  PRIMARY KEY(notice_id, subscription_id)
);
CREATE INDEX push_due ON push_jobs(due);
CREATE FUNCTION queue_inbox_push() RETURNS trigger
LANGUAGE plpgsql SET search_path = calvario, pg_catalog AS $$
DECLARE
  created_ms BIGINT := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
BEGIN
  INSERT INTO push_jobs(notice_id, subscription_id, due)
    SELECT NEW.notice_id, p.id, created_ms
    FROM push_subscriptions p JOIN sessions s ON s.token = p.session_token
    WHERE p.member_id = NEW.member_id AND s.expires > created_ms;
  RETURN NEW;
END
$$;
CREATE TRIGGER inbox_push AFTER INSERT ON inbox
FOR EACH ROW EXECUTE FUNCTION queue_inbox_push();

